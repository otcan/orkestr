const checksum = "a".repeat(64);
const ref = "b".repeat(40);
const crate = (name, version, extra = "") => `[[package]]\nname = "${name}"\nversion = "${version}"\nsource = "${cratesIoSource}"\nchecksum = "${checksum}"\n${extra}`;
const member = `[[package]]\nname = "orkestr-v2-server"\nversion = "2.0.0-beta.6"\ndependencies = [\n "example",\n "other 1.2.3",\n]\n`;
const lockText = (...blocks) => `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n${blocks.join("\n")}`;
const lock = lockText(crate("example", "1.0.0"), crate("other", "1.2.3"), member);
const pkg = { package: "example", version: "1.0.0" };
const day = 86400000;
const exception = (now, patch = {}) => ({ package: "example", version: "1.0.0", advisoryId: "RUSTSEC-2026-0001", approvedBy: "owner", reviewRef: "ORK-615",
  approvedAt: new Date(now - day).toISOString(), expiresAt: new Date(now + day).toISOString(), rationale: "Not compiled into any workspace target.", ...patch });
const policy = { schemaVersion: 1, exceptions: [] };
const advisory = (patch = {}, affected = {}) => ({ id: "RUSTSEC-2026-0001", modified: "2026-10-01T00:00:00Z", aliases: ["GHSA-test-1234-abcd"],
  affected: [{ package: { ecosystem: "crates.io", name: "example" }, ranges: [{ type: "SEMVER", events: [{ introduced: "0.0.0-0" }, { fixed: "1.0.1" }] }], ...affected }], ...patch });

test("generated lock inventory separates registry crates from workspace members", () => {
  const result = parseCargoLock(lock);
  assert.deepEqual([result.lockVersion, result.entries, result.workspace], [4, 3, ["orkestr-v2-server"]]);
  assert.deepEqual(result.crates.map(row => `${row.package}@${row.version}`), ["example@1.0.0", "other@1.2.3"]);
});

test("malformed locks, unsupported sources and hand-edited shapes fail closed", () => {
  const bad = [
    lock.replace("version = 4", "version = 1"), lock.replace("version = 4\n", ""),
    lockText(crate("example", "1.0.0").replace(cratesIoSource, "git+https://example.invalid/repo#abc")),
    lockText(crate("example", "1.0.0").replace(cratesIoSource, "registry+https://mirror.invalid/index")),
    lockText(crate("example", "1.0.0").replace(`checksum = "${checksum}"\n`, "")),
    lockText(crate("example", "1.0.0").replace(checksum, "short")),
    lockText(crate("example", "1.0.0"), member.replace('version = "2.0.0-beta.6"\n', `version = "2.0.0-beta.6"\nchecksum = "${checksum}"\n`)),
    lockText(crate("example", "1.0.0"), crate("example", "1.0.0")),
    lockText(crate("example", "latest")), lockText(crate("bad name", "1.0.0")),
    lockText(crate("example", "1.0.0", 'replace = "other 1.2.3"\n')),
    lockText(crate("example", "1.0.0", "dependencies = [\n \"other\",\n")),
    lockText(crate("example", "1.0.0")) + "\n[[patch.unused]]\nname = \"x\"\nversion = \"1.0.0\"\n",
    lockText(crate("example", "1.0.0")) + "\n[metadata]\n", lockText(member), "", 7,
  ];
  for (const text of bad) assert.throws(() => parseCargoLock(text), undefined, String(text).slice(-80));
});

test("exceptions are exact, attributed, explained, bounded to seven days, and expired ones fail", () => {
  const now = Date.parse("2026-11-05T12:00:00Z");
  assert.equal(validateCargoPolicy({ schemaVersion: 1, exceptions: [exception(now)] }, now).exceptions.length, 1);
  for (const patch of [{ expiresAt: new Date(now - 1).toISOString() }, { approvedAt: new Date(now + 1).toISOString() },
    { expiresAt: new Date(now + 7 * day).toISOString() }, { rationale: " " }, { rationale: undefined }, { reviewRef: "none" },
    { approvedBy: "" }, { advisoryId: "" }, { version: "^1" }, { package: "bad name" }]) {
    assert.throws(() => validateCargoPolicy({ schemaVersion: 1, exceptions: [exception(now, patch)] }, now), /invalid_or_expired_cargo_exception/, JSON.stringify(patch));
  }
  assert.throws(() => validateCargoPolicy({ schemaVersion: 1, exceptions: [exception(now), exception(now)] }, now), /invalid_or_expired_cargo_exception/);
  assert.throws(() => validateCargoPolicy({ schemaVersion: 2, exceptions: [] }, now), /invalid_cargo_policy/);
});

test("vulnerable and unsound records block, maintenance notices are reported, unknown marks fail closed", () => {
  const now = Date.parse("2026-11-05T12:00:00Z");
  const mark = value => advisory({}, { database_specific: { informational: value } });
  const open = minimizeCargoAdvisory(pkg, advisory(), policy, now);
  assert.deepEqual([open.kind, open.status, open.fixedVersion, blocksCargoRelease(open)], ["vulnerability", "open", "1.0.1", true]);
  assert.deepEqual(Object.keys(open).sort(), ["advisoryId", "aliases", "fixedVersion", "kind", "modified", "package", "status", "version"]);
  for (const [value, kind, status] of [["unmaintained", "notice", "notice"], ["notice", "notice", "notice"], ["unsound", "unsound", "open"], ["something-new", "unknown", "open"]]) {
    const row = minimizeCargoAdvisory(pkg, mark(value), policy, now);
    assert.deepEqual([row.kind, row.status, blocksCargoRelease(row)], [kind, status, status === "open"], value);
  }
  const mixed = advisory(); mixed.affected.push({ package: { ecosystem: "crates.io", name: "example" }, database_specific: { informational: "unmaintained" } });
  assert.equal(minimizeCargoAdvisory(pkg, mixed, policy, now).kind, "vulnerability");
  const excepted = minimizeCargoAdvisory(pkg, advisory(), { schemaVersion: 1, exceptions: [exception(now)] }, now);
  assert.deepEqual([excepted.status, blocksCargoRelease(excepted)], ["approved_exception", false]);
  assert.equal(minimizeCargoAdvisory(pkg, advisory({ withdrawn: "2026-10-02T00:00:00Z" }), policy, now).status, "withdrawn");
  for (const broken of [advisory({ affected: [{ package: { ecosystem: "npm", name: "example" } }] }), advisory({ modified: "soon" }), advisory({ aliases: ["bad id"] }),
    advisory({ withdrawn: "yes" }), mark(7), advisory({}, { ranges: [{ type: "SEMVER", events: [{ fixed: "next" }] }] })]) {
    assert.throws(() => minimizeCargoAdvisory(pkg, broken, policy, now));
  }
});

test("a GitHub mirror of a RustSec record is one advisory, not two", () => {
  const rustsec = { ...pkg, advisoryId: "RUSTSEC-2026-0001", aliases: ["GHSA-test-1234-abcd"] };
  const mirror = { ...pkg, advisoryId: "GHSA-test-1234-abcd", aliases: ["RUSTSEC-2026-0001"] };
  const alone = { ...pkg, advisoryId: "GHSA-only-1234-abcd", aliases: ["CVE-2026-0001"] };
  assert.deepEqual(mergeAliases([mirror, rustsec, alone]).map(row => row.advisoryId), ["RUSTSEC-2026-0001", "GHSA-only-1234-abcd"]);
  assert.deepEqual(mergeAliases([{ ...mirror, version: "2.0.0" }, rustsec]).length, 2);
});

async function fixture(t, policyFile = policy) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "orkestr-cargo-scan-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.mkdir(path.join(root, "v2"));
  await fs.writeFile(path.join(root, lockPath), lock);
  const policyPath = path.join(root, "policy.json");
  await fs.writeFile(policyPath, JSON.stringify(policyFile));
  return { root, commit: ref, policyCommit: ref, reportPath: path.join(root, "evidence.json"), policyPath, verify: async () => {} };
}
const clean = async route => route === "/querybatch" ? { results: [{}, {}] } : assert.fail("no detail expected");
const vulnerable = async (route, body) => route === "/querybatch" ? { results: body.queries.map(query => query.package.name === "example" ? { vulns: [{ id: "RUSTSEC-2026-0001" }] } : {}) } : advisory();

test("clean scan binds commit, lock and policy digests and asks only for crates.io identities", async t => {
  const f = await fixture(t); const bodies = [];
  const report = await scanCargoLock({ ...f, request: async (route, body) => { bodies.push(body); return clean(route); } });
  assert.deepEqual([report.status, report.commit, report.counts.registryCrates, report.counts.workspaceEntries, report.counts.blocking], ["passed", ref, 2, 1, 0]);
  assert.match(report.lockSha256, /^[a-f0-9]{64}$/); assert.match(report.policySha256, /^[a-f0-9]{64}$/);
  assert.deepEqual(bodies[0].queries, [{ package: { ecosystem: "crates.io", name: "example" }, version: "1.0.0" }, { package: { ecosystem: "crates.io", name: "other" }, version: "1.2.3" }]);
  assert.deepEqual(JSON.parse(await fs.readFile(f.reportPath, "utf8")), report);
  await assert.rejects(scanCargoLock({ ...f, request: clean })); // never silently overwrite evidence
  await assert.rejects(scanCargoLock({ ...f, request: clean, reportPath: path.join(f.root, "missing/evidence.json") }));
});

test("a known advisory publishes a blocked result and a dated exception clears exactly that finding", async t => {
  const f = await fixture(t);
  const report = await scanCargoLock({ ...f, request: vulnerable });
  assert.deepEqual([report.status, report.counts.advisories, report.counts.blocking, report.newestAdvisoryModifiedAt], ["blocked", 1, 1, "2026-10-01T00:00:00.000Z"]);
  const g = await fixture(t, { schemaVersion: 1, exceptions: [exception(Date.now())] });
  const accepted = await scanCargoLock({ ...g, request: vulnerable });
  assert.deepEqual([accepted.status, accepted.counts.exceptions, accepted.findings[0].status], ["passed", 1, "approved_exception"]);
});

test("unavailable, truncated or mismatched advisory data and bad locks never produce green evidence", async t => {
  for (const request of [async () => { throw new Error("private error"); }, async () => ({ results: [{}] }), async () => ({ results: "none" }),
    async route => route === "/querybatch" ? { results: [{ vulns: [{ id: "RUSTSEC-2026-0001" }] }, {}] } : { ...advisory(), id: "RUSTSEC-2026-9999" }]) {
    const f = await fixture(t);
    await assert.rejects(scanCargoLock({ ...f, request }));
    await assert.rejects(fs.stat(f.reportPath));
  }
  const f = await fixture(t); let calls = 0;
  await fs.writeFile(path.join(f.root, lockPath), lock.replace(cratesIoSource, "git+https://example.invalid/repo"));
  await assert.rejects(scanCargoLock({ ...f, request: async () => { calls++; return { results: [] }; } }), /unsupported_lock_source/);
  await assert.rejects(scanCargoLock({ ...f, commit: "main", request: clean }), /explicit_cargo_scan_scope_required/);
  assert.equal(calls, 0);
});

test("unverified snapshot cannot query the service or publish coverage", async t => {
  const f = await fixture(t); let calls = 0;
  await assert.rejects(scanCargoLock({ ...f, verify: verifyCargoSnapshot, request: async () => { calls++; return { results: [{}, {}] }; } }));
  assert.equal(calls, 0);
  await assert.rejects(fs.stat(f.reportPath));
});

