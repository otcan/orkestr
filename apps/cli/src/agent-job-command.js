// CLI for Agent Jobs. These commands work directly on the local store under
// ORKESTR_HOME, so they need no running server; when the server is running,
// run leases keep the two from driving the same run at once.
import fs from "node:fs/promises";
import path from "node:path";
import { admitRun, registerJobFiles, requestCancel } from "../../../packages/core/src/agent-job-admission.js";
import { getRunAudit } from "../../../packages/core/src/agent-job-audit.js";
import { decideApproval, listApprovals, listRunEffects } from "../../../packages/core/src/agent-job-ledger.js";
import { driveRun } from "../../../packages/core/src/agent-job-runner.js";
import { getRun, listAttemptsSync, listRuns, openAgentJobDb } from "../../../packages/core/src/agent-job-store.js";
import { relayAgentJobNotifications } from "../../../packages/connectors/src/agent-job-notification-relay.js";
import { installAgentJobProviderProbes } from "../../../packages/connectors/src/agent-job-provider-probes.js";
import { connectProviderHint, connectedAgentJobProviders } from "../../../packages/core/src/agent-job-providers.js";

// Hand notification intents to the connector outbox after local driving.
async function drive(runId, options, env) {
  installAgentJobProviderProbes();
  const result = await driveRun(runId, options, env);
  await relayAgentJobNotifications({}, env);
  return result;
}

export const agentJobUsage = [
  "  orkestr init [dir] [--force]",
  "  orkestr run <job.yaml|dir> [--job name] [--idempotency-key key] [--no-wait] [--json]",
  "  orkestr jobs list [--job name] [--state state] [--limit n] [--json]",
  "  orkestr jobs status <run-id> [--json]",
  "  orkestr jobs approvals [--run run-id] [--all] [--json]",
  "  orkestr jobs approve|deny <approval-id> [--comment text] [--no-drive] [--json]",
  "  orkestr jobs cancel <run-id> [--json]",
].join("\n");

// The example job `orkestr init` writes for the connected provider(s).
export function exampleJobYaml({ provider = "codex", fallback = null } = {}) {
  return `# Example Agent Job (docs/spec/agent-job.md). Generated by \`orkestr init\`.
# Runs on your connected ${provider === "codex" ? "Codex" : "Claude"} login. Edit the prompt, add triggers
# (webhook, schedule, whatsapp) and tool permissions, then: orkestr run <dir>
apiVersion: orkestr/v0
kind: AgentJob
metadata:
  name: hello-job
  description: Summarize what changed in the current repository.
triggers:
  - type: api
agent:
  provider: ${provider}${fallback ? `
  fallback:
    - provider: ${fallback}` : ""}
task:
  prompt: Summarize the most recent changes in this repository in five bullet points.
permissions:
  tools:
    allow: []
runtime:
  max_attempts: 3
  timeout: 15m
  retry:
    initial_delay: 30s
    max_delay: 5m
`;
}

function parseFlags(args, { boolean = [], string = [] } = {}) {
  const flags = {};
  const positional = [];
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    const key = arg.startsWith("--") ? arg.slice(2) : "";
    if (key && boolean.includes(key)) flags[key] = true;
    else if (key && string.includes(key)) {
      if (index + 1 >= args.length) throw new Error(`Missing value for --${key}\nUsage:\n${agentJobUsage}`);
      flags[key] = args[++index];
    } else if (key) throw new Error(`Unknown option --${key}\nUsage:\n${agentJobUsage}`);
    else positional.push(arg);
  }
  return { flags, positional };
}

function writeJson(ctx, value) {
  ctx.stdout.write(`${JSON.stringify(value, null, 2)}\n`);
}

function describe(result) {
  const extra = result.approvalId ? ` approval=${result.approvalId}` : result.reason ? ` reason=${result.reason}` : "";
  return `run ${result.runId}: ${result.state}${extra}`;
}

function exitCodeFor(state) {
  return ["failed", "cancelled"].includes(state) ? 1 : 0;
}

export async function initCommand(args, ctx) {
  const { flags, positional } = parseFlags(args, { boolean: ["force"] });
  const env = ctx.env || process.env;
  installAgentJobProviderProbes();
  const connected = await connectedAgentJobProviders(env);
  if (!connected.length) throw new Error(connectProviderHint);
  const dir = path.resolve(positional[0] || ".");
  const file = path.join(dir, "jobs", "hello-job.yaml");
  const exists = await fs.stat(file).then(() => true, () => false);
  if (exists && !flags.force) throw new Error(`${file} already exists (use --force to overwrite)`);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, exampleJobYaml({ provider: connected[0], fallback: connected[1] || null }));
  ctx.stdout.write(`Wrote ${file} (provider: ${connected[0]})\nNext: orkestr run ${path.relative(process.cwd(), dir) || "."}\n`);
  return 0;
}

export async function runJobCommand(args, ctx) {
  const env = ctx.env || process.env;
  const { flags, positional } = parseFlags(args, { boolean: ["json", "no-wait"], string: ["job", "idempotency-key"] });
  if (!positional[0]) throw new Error(`Usage:\n${agentJobUsage}`);
  const registered = await registerJobFiles(positional[0], env);
  const selected = flags.job ? registered.filter((entry) => entry.name === flags.job) : registered;
  if (!selected.length) throw new Error(`No job named ${flags.job}`);
  if (selected.length > 1) throw new Error(`Several jobs found (${selected.map((entry) => entry.name).join(", ")}); pick one with --job`);
  installAgentJobProviderProbes();
  let admitted;
  try {
    admitted = await admitRun({ job: selected[0].name, type: "api", dedupeKey: flags["idempotency-key"] || "" }, env);
  } catch (error) {
    if (error?.code === "provider_not_connected") throw new Error(`${connectProviderHint} (job ${selected[0].name} uses ${error.provider}, which is not connected: ${error.reason})`);
    throw error;
  }
  const { run, deduplicated } = admitted;
  const result = flags["no-wait"]
    ? { runId: run.id, state: run.state }
    : await drive(run.id, { waitForBackoff: true, baseDir: path.dirname(selected[0].source) }, env);
  if (flags.json) writeJson(ctx, { ...result, job: run.job, deduplicated });
  else {
    ctx.stdout.write(`${describe(result)}${deduplicated ? " (deduplicated)" : ""}\n`);
    if (result.approvalId) ctx.stdout.write(`Approve with: orkestr jobs approve ${result.approvalId}\n`);
    if (result.state === "succeeded" && result.output) ctx.stdout.write(`output: ${JSON.stringify(result.output)}\n`);
  }
  return exitCodeFor(result.state);
}

async function listCommand(args, ctx) {
  const { flags } = parseFlags(args, { boolean: ["json"], string: ["job", "state", "limit"] });
  const runs = await listRuns({ job: flags.job || "", state: flags.state || "", limit: Number(flags.limit) || 50 }, ctx.env);
  if (flags.json) {
    writeJson(ctx, { runs });
    return 0;
  }
  if (!runs.length) ctx.stdout.write("No agent job runs.\n");
  for (const run of runs) ctx.stdout.write(`${run.id}  ${run.job}  ${run.state}${run.reason ? ` (${run.reason})` : ""}  attempts=${run.attemptCount}  ${run.createdAt}\n`);
  return 0;
}

async function statusCommand(args, ctx) {
  const { flags, positional } = parseFlags(args, { boolean: ["json"] });
  const run = await getRun(positional[0], ctx.env);
  if (!run) throw new Error(`run_not_found: ${positional[0] || ""}`);
  const db = await openAgentJobDb(ctx.env);
  const detail = {
    run: { ...run, trigger: { ...run.trigger, event: undefined } },
    attempts: listAttemptsSync(db, run.id),
    effects: await listRunEffects(run.id, ctx.env),
    approvals: await listApprovals({ runId: run.id }, ctx.env),
    audit: run.sealed ? await getRunAudit(run.id, ctx.env) : null,
  };
  if (flags.json) {
    writeJson(ctx, detail);
    return 0;
  }
  ctx.stdout.write(`${run.id}  job=${run.job}  state=${run.state}${run.reason ? ` (${run.reason})` : ""}  spec=${run.specHash.slice(0, 19)}\n`);
  for (const attempt of detail.attempts) ctx.stdout.write(`  attempt ${attempt.n}  ${attempt.provider}  ${attempt.state}  ${attempt.endReason || ""}\n`);
  for (const effect of detail.effects) ctx.stdout.write(`  effect ${effect.tool}  ${effect.state}${effect.ref ? `  ${effect.ref}` : ""}\n`);
  for (const approval of detail.approvals) ctx.stdout.write(`  approval ${approval.approvalId}  ${approval.tool}  ${approval.state}  (${approval.reason})\n`);
  return 0;
}

async function approvalsCommand(args, ctx) {
  const { flags } = parseFlags(args, { boolean: ["json", "all"], string: ["run"] });
  const approvals = await listApprovals({ runId: flags.run || "", state: flags.all ? "" : "pending" }, ctx.env);
  if (flags.json) {
    writeJson(ctx, { approvals });
    return 0;
  }
  if (!approvals.length) ctx.stdout.write("No approvals.\n");
  for (const approval of approvals) {
    ctx.stdout.write(`${approval.approvalId}  run=${approval.runId}  ${approval.tool}  ${approval.state}  (${approval.reason})  expires=${approval.expiresAt}\n`);
  }
  return 0;
}

async function decideCommand(decision, args, ctx) {
  const { flags, positional } = parseFlags(args, { boolean: ["json", "no-drive"], string: ["comment", "by"] });
  const approval = await decideApproval(positional[0], {
    decision,
    by: flags.by || `cli:${ctx.env?.USER || "operator"}`,
    comment: flags.comment || "",
  }, ctx.env);
  const result = flags["no-drive"] ? null : await drive(approval.runId, { waitForBackoff: true }, ctx.env);
  if (flags.json) {
    writeJson(ctx, { approval, run: result });
    return 0;
  }
  ctx.stdout.write(`approval ${approval.approvalId}: ${approval.state}\n`);
  if (result) ctx.stdout.write(`${describe(result)}\n`);
  return 0;
}

async function cancelCommand(args, ctx) {
  const { flags, positional } = parseFlags(args, { boolean: ["json"] });
  await requestCancel(positional[0], { by: `cli:${ctx.env?.USER || "operator"}` }, ctx.env);
  // Finalizes now when no other process holds the run; otherwise the holder
  // stops before its next effect.
  const result = await drive(positional[0], {}, ctx.env);
  if (flags.json) {
    writeJson(ctx, result);
    return 0;
  }
  ctx.stdout.write(result.leased === false ? `run ${positional[0]}: cancel requested (another process is driving it)\n` : `${describe(result)}\n`);
  return 0;
}

export async function agentJobsCommand(subcommand, args, ctx) {
  if (subcommand === "list" || subcommand === "runs") return listCommand(args, ctx);
  if (subcommand === "status" || subcommand === "show") return statusCommand(args, ctx);
  if (subcommand === "approvals") return approvalsCommand(args, ctx);
  if (subcommand === "approve") return decideCommand("approved", args, ctx);
  if (subcommand === "deny") return decideCommand("denied", args, ctx);
  if (subcommand === "cancel") return cancelCommand(args, ctx);
  throw new Error(`Usage:\n${agentJobUsage}`);
}

export const agentJobSubcommands = Object.freeze(["list", "runs", "status", "show", "approvals", "approve", "deny", "cancel"]);
